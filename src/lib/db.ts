import "server-only";
import postgres from "postgres";

/**
 * PostgreSQL lewat postgres.js (tanpa dependensi lain). Env: DATABASE_URL.
 *
 * Hemat koneksi: pool kecil (4) dan koneksi yang menganggur 2 menit ditutup, karena tiap koneksi
 * adalah satu proses di server database. Pernyataan disiapkan (prepared) otomatis per koneksi.
 * Kolom waktu memakai detik epoch (bigint), sama seperti sebelum pindah dari SQLite.
 */

export type Sql = postgres.Sql<{ bigint: number }>;
export type Tx = postgres.TransactionSql<{ bigint: number }>;

